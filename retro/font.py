GLYPHS = {k: v.split("|") for k, v in _G.items()}
ADVANCE, HEIGHT = 6, 7
_cache: dict = {}


def width(text: str, scale: int = 1) -> int:
    return max(len(text) * ADVANCE - 1, 0) * scale


def render(text: str, color, scale: int = 1) -> pygame.Surface:
    """Text as a transparent surface. Lowercase is drawn as uppercase."""
    key = (text, tuple(color), scale)
    if key in _cache:
        return _cache[key]
    text = text.upper().replace("_", " ")
    surf = pygame.Surface((max(width(text), 1), HEIGHT), pygame.SRCALPHA)
    for i, ch in enumerate(text):
        rows = GLYPHS.get(ch, GLYPHS["?"])
        for y, row in enumerate(rows):
            for x, bit in enumerate(row):
                if bit == "#":
                    surf.set_at((i * ADVANCE + x, y), color)
    if scale != 1:
        surf = pygame.transform.scale(surf, (surf.get_width() * scale, HEIGHT * scale))
    if len(_cache) > 600:
        _cache.clear()
    _cache[key] = surf
    return surf


def draw(target, text, x, y, color, scale=1, align="left", shadow=(20, 12, 24)):
    """Draw text. align: left / center / right (x is that edge or the center)."""
    img = render(text, color, scale)
    if align == "center":
        x -= img.get_width() // 2
    elif align == "right":
        x -= img.get_width()
    if shadow is not None:
        off = 1 if scale < 3 else 2   # thin drop shadow keeps big text readable
        target.blit(render(text, shadow, scale), (x + off, y + off))
    target.blit(img, (x, y))
    return img.get_width()
