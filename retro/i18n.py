LANGS = ("en", "es")


class Text:
    def __init__(self, lang: str = "en"):
        self.lang = lang if lang in LANGS else "en"

    def toggle(self):
        self.lang = "es" if self.lang == "en" else "en"

    def __call__(self, key: str, **kw) -> str:
        pair = STRINGS.get(key)
        if pair is None:
            return key.format(**kw) if kw else key
        return pair[LANGS.index(self.lang)].format(**kw)
